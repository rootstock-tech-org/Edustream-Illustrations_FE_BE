/**
 * Vision Feed (/camera)
 * ======================
 * Renders the RGB and depth streams and — the part that matters — says which
 * source is on screen.
 *
 * The page can show two different things: frames from a physical RealSense
 * (`camera_views`, only present in HYBRID mode with the camera streaming), or
 * the simulation's synthetic imagery (`sensor_views`). They look plausible
 * either way, so falling back silently made a dead camera indistinguishable
 * from a working one. Every frame is labelled, and when the live feed is
 * expected but missing the reason is shown.
 */
(function () {
    'use strict';

    const socket = io();

    let lastSource = null;     // 'live' | 'synthetic'
    let lastReady = null;
    let views = null;          // SensorViews — drives the ToF panel
    let pointCloud = null;     // PointCloudRenderer — the 3D panel

    function el(id) { return document.getElementById(id); }

    function setFrame(imgId, placeholderId, b64) {
        if (!b64) return false;
        const img = el(imgId);
        if (!img) return false;
        img.src = 'data:image/jpeg;base64,' + b64;
        img.style.display = 'block';
        const ph = el(placeholderId);
        if (ph) ph.style.display = 'none';
        return true;
    }

    /**
     * Reflect camera state in the topbar pill, the per-panel source badges and
     * the notice strip. Only touches the DOM when something actually changed —
     * this runs at the state-update rate.
     */
    function renderStatus(cam) {
        if (!cam) return;
        if (cam.source === lastSource && cam.ready === lastReady) return;
        lastSource = cam.source;
        lastReady = cam.ready;

        const live = cam.source === 'live';

        const pill = el('camera-state-pill');
        if (pill) {
            pill.className = 'pill ' + (live ? 'pill-safe' : 'pill-warn');
            pill.innerHTML = '<span class="dot' + (live ? ' dot-live' : '') + '"></span>';
            pill.appendChild(document.createTextNode(live ? 'Live sensor' : 'Synthetic'));
        }

        const badge = live ? 'D435i · live' : 'Simulated';
        ['rgb-source', 'depth-source'].forEach(id => {
            const b = el(id);
            if (b) {
                b.textContent = badge;
                b.className = 'pill ' + (live ? 'pill-safe' : '');
            }
        });

        const notice = el('camera-notice');
        if (!notice) return;
        if (live) {
            notice.style.display = 'none';
            return;
        }
        // Not live. Whether that is a fault or just the default mode depends on
        // whether this build was ever meant to drive a camera.
        notice.style.display = '';
        notice.className = 'callout ' + (cam.supported ? 'callout-warn' : '');
        notice.innerHTML =
            '<strong>' + (cam.supported ? 'Live camera unavailable' : 'Synthetic feed') + '</strong>' +
            '<div class="t-meta" id="camera-notice-body"></div>';
        el('camera-notice-body').textContent = cam.error
            ? cam.error
            : (cam.supported
                ? 'The camera is not streaming. Use Reconnect Sensor to retry.'
                : 'Running in ' + (cam.mode || 'MOCK') + ' mode — these frames are generated by the ' +
                  'simulation. Set SMARTSEG_SENSOR_MODE=HYBRID on a machine with an Intel ' +
                  'RealSense D435i attached to show the live feed here.');
    }

    socket.on('connect', () => {
        if (window.SmartSegUI) SmartSegUI.markConnected();
    });

    socket.on('disconnect', () => {
        if (window.SmartSegUI) SmartSegUI.markDisconnected();
    });

    socket.on('state_update', (data) => {
        if (window.SmartSegUI) SmartSegUI.touch();
        renderStatus(data.camera);

        // ToF depth map and the 3D point cloud, which moved here from the
        // Overview. Same dispatch the other pages use.
        if (views && window.SmartSegPanels) SmartSegPanels.apply(data, views, pointCloud);
        if (pointCloud && pointCloud.setBeltWidth && typeof data.belt_width === 'number') {
            pointCloud.setBeltWidth(data.belt_width);
        }

        // Prefer the real camera. `camera_views` only exists when hardware is
        // actually producing frames, so this is also the source of truth for
        // which stream the badges describe.
        const cv = data.camera_views;
        const sv = data.sensor_views;

        setFrame('rgb-image', 'rgb-placeholder', (cv && cv.rgb) || (sv && sv.rgb_image));
        setFrame('depth-image', 'depth-placeholder', (cv && cv.depth) || (sv && sv.depth_image));
    });

    document.addEventListener('DOMContentLoaded', function () {
        if (window.SensorViews) views = new SensorViews();
        if (window.PointCloudRenderer) {
            pointCloud = new PointCloudRenderer('pointcloud-container', 'three-canvas');
        }

        const reset = el('btn-reset-view');
        if (reset) reset.addEventListener('click', () => {
            if (pointCloud && pointCloud.resetView) pointCloud.resetView();
        });

        const toggle = el('btn-toggle-3d');
        if (toggle) toggle.addEventListener('click', () => {
            const body = el('pointcloud-body');
            if (!body) return;
            const hidden = body.style.display === 'none';
            body.style.display = hidden ? '' : 'none';
            toggle.textContent = hidden ? 'Hide' : 'Show';
            // Pause the render loop while hidden — it is a full WebGL scene.
            if (pointCloud) pointCloud.paused = !hidden;
        });
    });

    const reconnectBtn = el('reconnect-btn');
    if (reconnectBtn) {
        reconnectBtn.addEventListener('click', () => {
            const run = () => fetch('/api/reconnect_camera', { method: 'POST' })
                .then(res => res.json())
                .then(data => {
                    // Force a re-render: the status may be identical to the one
                    // already on screen, and the operator still needs feedback.
                    lastSource = lastReady = null;
                    renderStatus(data.camera);
                    if (window.SmartSegUI) {
                        const ok = data.camera && data.camera.ready;
                        SmartSegUI.toast(
                            ok ? 'Camera connected' : 'Camera not detected',
                            (data.camera && data.camera.error) || data.status || '',
                            ok ? 'info' : 'warn');
                    }
                });

            if (window.SmartSegUI) {
                SmartSegUI.driveCommand(reconnectBtn, 'RECONNECTING…', 'Reconnect attempted', run);
            } else {
                run().catch(err => console.error('[Camera] reconnect failed', err));
            }
        });
    }
})();
